"""Render a report as Markdown, HTML or JSON. Everything taken from the capture is escaped."""

from __future__ import annotations

import html
import json
from datetime import UTC, datetime

from . import __version__
from .analyze import Report
from .story import duration_text, size_text

DISCLAIMER = (
    "Notes under *Worth a look* come from simple rules, not from a verdict. They point at "
    "traffic worth checking against what you know about the network."
)


def stamp(ns: int) -> str:
    if ns <= 0:
        return "(no time)"
    try:
        moment = datetime.fromtimestamp(ns // 1_000_000_000, UTC)
    except (OverflowError, OSError, ValueError):
        return "(no time)"
    return moment.strftime("%Y-%m-%dT%H:%M:%S") + f".{(ns // 1_000_000) % 1000:03d}Z"


def cite(first: int, last: int) -> str:
    return f"pkt {first}" if first == last else f"pkt {first}–{last}"


def _facts(r: Report) -> list[str]:
    a = r.analysis
    span = duration_text(max(0, a.last_ts - a.first_ts))
    return [
        f"{a.packets} packets over {span}, "
        f"from {stamp(a.first_ts)} to {stamp(a.last_ts)} ({r.format})",
        f"{len(a.flows)} conversations between {len(a.hosts)} hosts",
        "protocols: " + (", ".join(f"{k} {v}" for k, v in sorted(a.protocols.items())) or "none"),
    ]


def _quality(r: Report) -> list[str]:
    a = r.analysis
    lines = list(r.warnings)
    if a.malformed:
        lines.append(f"{a.malformed} packet(s) could not be decoded and were left out.")
    for what, n in sorted(a.unsupported.items()):
        lines.append(f"{n} packet(s) not analysed: {what}.")
    if a.fragments:
        lines.append(f"{a.fragments} IP fragment(s) seen; fragments are not reassembled.")
    return lines


def to_markdown(r: Report, *, max_events: int = 200) -> str:
    story = [e for e in r.events]
    notable = [e for e in story if e.notable]
    out = [f"# PacketStory: {_md(r.name)}", ""]
    out += [f"- {line}" for line in _facts(r)]
    out += ["", "## The story", ""]
    for e in story[:max_events]:
        out.append(f"- `{stamp(e.ts_ns)}` [{cite(e.first_pkt, e.last_pkt)}] {_md(e.text)}")
    if len(story) > max_events:
        out.append(
            f"- … {len(story) - max_events} more event(s); raise `--max-events` to see them."
        )
    if not story:
        out.append("Nothing to tell: no conversations were found in this capture.")
    out += ["", "## Worth a look", ""]
    out += [f"- [{cite(e.first_pkt, e.last_pkt)}] {_md(e.text)}" for e in notable] or [
        "Nothing stood out to the rules PacketStory applies."
    ]
    out += [
        "",
        f"_{DISCLAIMER}_",
        "",
        "## Hosts",
        "",
        "| Host | Packets sent | Bytes sent |",
        "|---|---:|---:|",
    ]
    a = r.analysis
    for addr, s in sorted(a.hosts.items(), key=lambda kv: (-kv[1].bytes, kv[0]))[:25]:
        label = f"{a.names[addr]} ({addr})" if addr in a.names else addr
        out.append(f"| {_md(label)} | {s.packets} | {size_text(s.bytes)} |")
    out += ["", "## Capture quality", ""]
    out += [f"- {_md(line)}" for line in _quality(r)] or ["No problems found reading the capture."]
    out += ["", f"_Generated by PacketStory {__version__}._", ""]
    return "\n".join(out)


def _md(text: str) -> str:
    """Make text from the capture inert in Markdown: no HTML, links, emphasis or table breaks."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for ch in ("\\", "`", "*", "_", "[", "]", "|"):
        text = text.replace(ch, "\\" + ch)
    return text.replace("\n", " ").replace("\r", " ")


def to_html(r: Report, *, max_events: int = 200) -> str:
    esc = html.escape
    a = r.analysis
    parts = [
        "<!doctype html><html lang=en><meta charset=utf-8>",
        f"<title>PacketStory: {esc(r.name)}</title>",
        "<style>body{font:16px/1.5 system-ui,sans-serif;max-width:60rem;margin:2rem auto;"
        "padding:0 1rem;"
        "background:#fff;color:#111}code{font-family:ui-monospace,monospace;color:#555}"
        ".n{border-left:4px solid #e0652f;padding-left:.6rem}li{margin:.3rem 0}"
        "@media(prefers-color-scheme:dark){body{background:#0c1220;color:#e6ebf5}"
        "code{color:#99a7bc}}</style>",
        f"<h1>PacketStory: {esc(r.name)}</h1><ul>",
        *[f"<li>{esc(line)}</li>" for line in _facts(r)],
        "</ul><h2>The story</h2><ul>",
    ]
    for e in r.events[:max_events]:
        cls = ' class="n"' if e.notable else ""
        parts.append(
            f"<li{cls}><code>{esc(stamp(e.ts_ns))} {esc(cite(e.first_pkt, e.last_pkt))}</code> "
            f"{esc(e.text)}</li>"
        )
    if len(r.events) > max_events:
        parts.append(f"<li>… {len(r.events) - max_events} more event(s).</li>")
    parts.append("</ul><h2>Worth a look</h2><ul>")
    notable = [e for e in r.events if e.notable]
    parts += [
        f"<li>{esc(e.text)} <code>{esc(cite(e.first_pkt, e.last_pkt))}</code></li>" for e in notable
    ] or ["<li>Nothing stood out to the rules PacketStory applies.</li>"]
    parts.append(
        f"</ul><p><em>{esc(DISCLAIMER.replace('*', ''))}</em></p><h2>Hosts</h2>"
        "<table><tr><th>Host<th>Packets sent<th>Bytes sent"
    )
    for addr, s in sorted(a.hosts.items(), key=lambda kv: (-kv[1].bytes, kv[0]))[:25]:
        label = f"{a.names[addr]} ({addr})" if addr in a.names else addr
        parts.append(f"<tr><td>{esc(label)}<td>{s.packets}<td>{esc(size_text(s.bytes))}")
    parts.append("</table><h2>Capture quality</h2><ul>")
    parts += [f"<li>{esc(line)}</li>" for line in _quality(r)] or [
        "<li>No problems found reading the capture.</li>"
    ]
    parts.append(f"</ul><p><small>Generated by PacketStory {esc(__version__)}.</small></p>")
    return "\n".join(parts) + "\n"


def to_json(r: Report) -> str:
    a = r.analysis
    doc = {
        "tool": f"packetstory {__version__}",
        "capture": {
            "name": r.name, "format": r.format, "packets": a.packets,
            "first_ts_ns": a.first_ts, "last_ts_ns": a.last_ts,
            "malformed": a.malformed, "unsupported": a.unsupported, "fragments": a.fragments,
            "warnings": r.warnings,
        },
        "events": [
            {"ts": stamp(e.ts_ns), "first_packet": e.first_pkt, "last_packet": e.last_pkt,
             "kind": e.kind, "notable": e.notable, "text": e.text}
            for e in r.events
        ],
        "hosts": {h: {"packets": s.packets, "bytes": s.bytes} for h, s in sorted(a.hosts.items())},
        "names": dict(sorted(a.names.items())),
    }  # fmt: skip
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"
