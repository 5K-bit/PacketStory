"""Tell the story of the lab capture, end to end, and record the evidence.

    python examples/acceptance.py --out docs/evidence

The capture ``examples/lab/lab.pcap`` is synthetic (see ``lab_builder.py``): a workstation
browses, fails to resolve a few names, sends credentials in cleartext, and a scanner walks 30
ports on a jump host. The transcript is deterministic; a test compares it with the recorded one.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "examples"))

import lab_builder  # noqa: E402

from packetstory.cli import main  # noqa: E402

LAB = ROOT / "examples" / "lab" / "lab.pcap"


def run_scenario(out_dir: Path) -> str:
    out_dir.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [
        "# examples/lab/lab.pcap is generated by examples/lab_builder.py from documentation-range",
        "# addresses; nothing in it was captured from a real network.",
    ]

    def run(*argv: str, show: int | None = None) -> None:
        lines.append(f"$ packetstory {' '.join(argv)}")
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = main(list(argv))
        text = buf.getvalue().rstrip("\n").splitlines()
        shown = text if show is None else text[:show]
        lines.extend(shown)
        if show is not None and len(text) > show:
            lines.append(f"... ({len(text) - show} more lines)")
        lines.append(f"[exit {code}]")

    cap = "examples/lab/lab.pcap"
    ok = LAB.read_bytes() == lab_builder.lab_pcap()
    lines.append(f"# checked-in capture matches the builder: {'yes' if ok else 'NO'}")
    run("summary", str(LAB.relative_to(ROOT)))
    run("flows", cap, "--limit", "6")
    run("story", cap, "--max-events", "40")
    for fmt, name in (("md", "story.md"), ("html", "story.html"), ("json", "story.json")):
        run("story", cap, "--format", fmt, "--out", str(out_dir / name))
        (out_dir / name).write_text(
            (out_dir / name).read_text(encoding="utf-8").replace(str(ROOT), "."),
            encoding="utf-8", newline="\n",
        )  # fmt: skip
    return "\n".join(lines).replace(str(out_dir), "<out>") + "\n"


def main_cli() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    text = run_scenario(args.out)
    (args.out / "acceptance-transcript.txt").write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main_cli()
